#!/usr/bin/env python3
"""Write manuscript/numbers.tex: LaTeX macros for every simulated number quoted in the text and table.

Input : data/tmd_table.csv, data/density_table.csv (from plot_results.py)
Output: manuscript/numbers.tex, \\input by main.tex. Rerun after every refit so the text never goes stale.

Macro names (LaTeX names cannot contain digits, so the dial value is spelled out):
  \\tmdC<Key>      maximum in degrees Celsius, rounded to whole degrees, with sign ("+49", "-46", "3.8" for lambda = 1)
  \\tmdK<Key>      maximum in kelvin, one decimal
  \\tmdRow<Key>    table cells "T_MD (deg C) +- err & rho_max" (or "below X" for an upper bound)
  \\hbMax<Key>     hydrogen bonds per molecule at the maximum
  \\tmdPM<Key>     "T_MD +- err" in degrees Celsius (math mode)
  \\tmdLoC<Key>, \\tmdHiC<Key>, \\edgePct<Key>   16-84 % range of all Monte Carlo refits (deg C) and the
                  percentage of refits stuck at the edge of the fit window; rows with > 10 % get a table note "a"
  \\TminC<Key>     coldest temperature used in the fits (deg C)
Keys: OneOhFive, One, NineSevenFive, NineFive, NineTwoFive, Nine, EightFive, SPCE, TIPthree
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
KEYS = {"t4p2005_l1.05": "OneOhFive", "t4p2005_l1.00": "One", "t4p2005_l0.97": "NineSevenFive",
        "t4p2005_l0.95": "NineFive", "t4p2005_l0.93": "NineTwoFive", "t4p2005_l0.90": "Nine",
        "t4p2005_l0.85": "EightFive", "spce": "SPCE", "tip3p": "TIPthree"}
MINUS = "$-$"
VEGA2005 = {"spce": 241.0, "tip3p": 182.0}     # literature T_MD (K), Vega & Abascal, JCP 123, 144504 (2005)
FIG4_SET = ["t4p2005_l1.05", "t4p2005_l1.00", "t4p2005_l0.95", "t4p2005_l0.90", "spce", "tip3p"]   # triangles in fig 4(a)


def signed(x, nd=0):
    s = f"{abs(x):.{nd}f}"
    return (MINUS if x < 0 else "+") + s


def main():
    rows = {r["model"]: r for r in csv.DictReader(open(os.path.join(BASE, "data", "tmd_table.csv")))}
    dens = list(csv.DictReader(open(os.path.join(BASE, "data", "density_table.csv"))))
    out = ["% Generated by analysis/make_numbers.py -- do not edit by hand."]
    hbs = []
    for model, key in KEYS.items():
        r = rows.get(model)
        if r is None:
            out.append(f"\\newcommand{{\\tmdC{key}}}{{\\textcolor{{red}}{{?}}}}")
            out.append(f"\\newcommand{{\\tmdK{key}}}{{\\textcolor{{red}}{{?}}}}")
            out.append(f"\\newcommand{{\\tmdRow{key}}}{{\\textcolor{{red}}{{?}} & }}")
            out.append(f"\\newcommand{{\\hbMax{key}}}{{\\textcolor{{red}}{{?}}}}")
            continue
        if r["status"] == "ok":
            tk, ek = float(r["TMD_K"]), float(r["TMD_err_K"])
            tc = tk - 273.15
            txt = f"{tc:.1f}" if key == "One" else signed(tc)
            out.append(f"\\newcommand{{\\tmdC{key}}}{{{txt}}}")
            out.append(f"\\newcommand{{\\tmdK{key}}}{{{tk:.1f}}}")
            cell = f"${tc:.1f}\\pm{ek:.1f}$"
            fin = float(r.get("frac_fits_inside") or 1.0)
            if fin < 0.9:     # many refits stuck at the window edge: quote the 16-84 % range of all refits instead
                up, dn = float(r["TMD_p84_K"]) - tk, tk - float(r["TMD_p16_K"])
                cell = f"${tc:.1f}^{{+{up:.1f}}}_{{-{dn:.1f}}}$"
            out.append(f"\\newcommand{{\\tmdPM{key}}}{{{cell}}}")
            note = "\\textsuperscript{a}" if fin < 0.9 else ""      # maximum poorly bracketed: see the table note
            out.append(f"\\newcommand{{\\tmdNote{key}}}{{{note}}}")      # goes after the model name in the table
            out.append(f"\\newcommand{{\\tmdRow{key}}}{{{cell} & {float(r['rho_max']):.4f}}}")
            if r.get("TMD_p16_K"):
                out.append(f"\\newcommand{{\\tmdLoC{key}}}{{{signed(float(r['TMD_p16_K']) - 273.15)}}}")
                out.append(f"\\newcommand{{\\tmdHiC{key}}}{{{signed(float(r['TMD_p84_K']) - 273.15)}}}")
                out.append(f"\\newcommand{{\\edgePct{key}}}{{{100 * (1 - fin):.0f}}}")
            hb = r.get("hbonds_at_TMD", "")
            if hb and hb != "nan":
                hbs.append(float(hb))
                out.append(f"\\newcommand{{\\hbMax{key}}}{{{float(hb):.2f}}}")
            else:
                out.append(f"\\newcommand{{\\hbMax{key}}}{{\\textcolor{{red}}{{?}}}}")
        else:
            out.append(f"\\newcommand{{\\tmdNote{key}}}{{}}")
            b = float(r["TMD_K"]) - 273.15
            word = "below" if r["status"] == "below" else "above"
            out.append(f"\\newcommand{{\\tmdC{key}}}{{{word} {signed(b)}}}")
            out.append(f"\\newcommand{{\\tmdK{key}}}{{{word} {float(r['TMD_K']):.0f}}}")
            out.append(f"\\newcommand{{\\tmdRow{key}}}{{{word} {signed(b)} & --}}")
            out.append(f"\\newcommand{{\\hbMax{key}}}{{--}}")
    # ---- numbers quoted in the running text (so that none is typed by hand)
    real = rows.get("real water (IAPWS)")
    t_real = float(real["TMD_K"]) if real else 277.13
    t1 = float(rows["t4p2005_l1.00"]["TMD_K"])
    ok = {m: float(r["TMD_K"]) for m, r in rows.items() if r["status"] == "ok" and m in KEYS}
    if "spce" in ok and "tip3p" in ok:
        out.append(f"\\newcommand{{\\gapSPCE}}{{{t_real - ok['spce']:.0f}}}")          # K colder than real water
        out.append(f"\\newcommand{{\\gapTIPthree}}{{{t_real - ok['tip3p']:.0f}}}")
        for m, key in (("spce", "SPCE"), ("tip3p", "TIPthree")):                    # vs Vega & Abascal 2005
            out.append(f"\\newcommand{{\\litGap{key}}}{{{ok[m] - VEGA2005[m]:.0f}}}")
    rho1 = float(rows["t4p2005_l1.00"]["rho_max"])
    out.append(f"\\newcommand{{\\rhoMaxOne}}{{{rho1:.4f}}}")
    if real:
        out.append(f"\\newcommand{{\\rhoExcessPctOne}}{{{100 * (rho1 / float(real['rho_max']) - 1):.2f}}}")
    if "t4p2005_l1.05" in ok and "t4p2005_l0.95" in ok:
        weak, strong = t1 - ok["t4p2005_l0.95"], ok["t4p2005_l1.05"] - t1
        out.append(f"\\newcommand{{\\shiftWeak}}{{{weak:.0f}}}")
        out.append(f"\\newcommand{{\\shiftStrong}}{{{strong:.0f}}}")
        out.append(f"\\newcommand{{\\shiftWeakApprox}}{{{round(weak, -1):.0f}}}")
    for lam, key in ((0.95, "NineFive"), (1.05, "OneOhFive"), (0.90, "Nine")):      # T_MD proportional to lambda^2
        out.append(f"\\newcommand{{\\estC{key}}}{{{signed(lam ** 2 * t1 - 273.15)}}}")
    fig4 = [float(rows[m]["hbonds_at_TMD"]) for m in FIG4_SET if rows.get(m, {}).get("status") == "ok"]
    if fig4:
        out.append(f"\\newcommand{{\\hbAvg}}{{{sum(fig4) / len(fig4):.1f}}}")   # dotted line in figure 4(a)
    # Exact mapping (Sec. III): (lambda, eps, T, P) has the same configurational statistics as (1, eps/lambda^2,
    # T/lambda^2, P/lambda^2). So each dial setting is TIP4P/2005 with its O-O Lennard-Jones depth changed by
    # 1/lambda^2, with maximum at T_MD/lambda^2.
    for m, key in KEYS.items():
        lam_m = rows.get(m, {}).get("lambda")
        if not lam_m or m not in ok or abs(float(lam_m) - 1) < 1e-9:
            continue
        l2 = float(lam_m) ** 2
        out.append(f"\\newcommand{{\\epsChange{key}}}{{{signed(100 * (1 / l2 - 1))}}}")       # per cent
        out.append(f"\\newcommand{{\\tmdEpsK{key}}}{{{ok[m] / l2:.0f}}}")
    # direct test of Eq. 6 (data/mapcheck.json, from analyze_runs on the cluster): TIP4P/2005 with eps/0.9025 at T/0.9025 and
    # 1/0.9025 bar versus lambda = 0.95 at T and 1 bar, for T = 270 K (key A) and 230 K (key B)
    mc_path = os.path.join(BASE, "data", "mapcheck.json")
    if os.path.exists(mc_path):
        import json, math
        mc = json.load(open(mc_path))
        for key, Tl, run in (("A", 270, "t4p2005_mapcheck/T299.169"), ("B", 230, "t4p2005_mapcheck/T254.848")):
            ref = [d for d in dens if d["model"] == "t4p2005_l0.95" and int(float(d["T_K"])) == Tl]
            if run in mc and "rho" in mc[run] and ref:
                r1, e1 = mc[run]["rho"], mc[run]["rho_sem"]
                r0, e0 = float(ref[0]["density_g_cm3"]), float(ref[0]["sem_g_cm3"])
                out.append(f"\\newcommand{{\\mapRun{key}}}{{{r1:.5f}}}")
                out.append(f"\\newcommand{{\\mapRunErr{key}}}{{{e1:.5f}}}")
                out.append(f"\\newcommand{{\\mapRef{key}}}{{{r0:.5f}}}")
                out.append(f"\\newcommand{{\\mapDiff{key}}}{{{abs(r1 - r0) / math.hypot(e0, e1):.1f}}}")   # in combined sigma
                out.append(f"\\newcommand{{\\mapHB{key}}}{{{mc[run].get('hb_mean', float('nan')):.3f}}}")
    # split of the lambda = 0.95 shift: lambda^2 rescaling of all energies + relatively stronger LJ attraction
    if "t4p2005_l0.95" in ok:
        l2 = 0.95 ** 2
        out.append(f"\\newcommand{{\\epsFactorNineFive}}{{{ok['t4p2005_l0.95'] / l2 / t1:.3f}}}")   # T_MD(eps/l2)/T_MD(1)
        out.append(f"\\newcommand{{\\lamSqNineFive}}{{{l2:.4f}}}")
    # ratio of each +-10 % shift to the lambda^2 estimate (the abstract quotes these, not the whole-range slope)
    if "t4p2005_l1.05" in ok and "t4p2005_l0.95" in ok:
        rw = (t1 - ok["t4p2005_l0.95"]) / (t1 - 0.95 ** 2 * t1)
        rs = (ok["t4p2005_l1.05"] - t1) / (1.05 ** 2 * t1 - t1)
        out.append(f"\\newcommand{{\\ratioLo}}{{{min(rw, rs):.1f}}}")
        out.append(f"\\newcommand{{\\ratioHi}}{{{max(rw, rs):.1f}}}")
        out.append(f"\\newcommand{{\\ratioWeak}}{{{rw:.1f}}}")      # lowering the electrostatic energy (lambda = 0.95)
    # local slopes (K per 1 % of lambda^2) at the two ends of the dial: the T_MD(lambda^2) curve is not straight
    if all(m in ok for m in ("t4p2005_l1.05", "t4p2005_l1.00", "t4p2005_l0.93", "t4p2005_l0.90")):
        top = (ok["t4p2005_l1.05"] - ok["t4p2005_l1.00"]) / ((1.05 ** 2 - 1.0) * 100)
        bot = (ok["t4p2005_l0.93"] - ok["t4p2005_l0.90"]) / ((0.925 ** 2 - 0.90 ** 2) * 100)
        out.append(f"\\newcommand{{\\slopeLocalTop}}{{{top:.1f}}}")
        out.append(f"\\newcommand{{\\slopeLocalBottom}}{{{bot:.1f}}}")
    # bond count and four-bonded fraction at the maximum without the least certain setting (lambda = 0.90)
    hb9 = [float(r["hbonds_at_TMD"]) for m, r in rows.items() if m in ok and m != "t4p2005_l0.90"]
    f49 = [float(r["frac4_at_TMD"]) for m, r in rows.items() if m in ok and m != "t4p2005_l0.90"]
    out.append(f"\\newcommand{{\\hbMaxNoNine}}{{{max(hb9):.2f}}}")
    out.append(f"\\newcommand{{\\fourMaxNoNine}}{{{100 * max(f49):.0f}}}")
    if "t4p2005_l0.95" in ok:
        l2 = 0.95 ** 2
        out.append(f"\\newcommand{{\\partLamNineFive}}{{{t1 - l2 * t1:.0f}}}")                        # K
        out.append(f"\\newcommand{{\\partEpsNineFive}}{{{l2 * (t1 - ok['t4p2005_l0.95'] / l2):.0f}}}")  # K
    # a mapping check students can run: lambda = 0.95 at 270 K <-> TIP4P/2005 with eps/0.9025 at 270/0.9025 K
    # (270 K, on the slope of the density curve, discriminates better than a point near the maximum)
    MAP_T = 270
    chk = [d for d in dens if d["model"] == "t4p2005_l0.95" and int(float(d["T_K"])) == MAP_T]
    if chk:
        l2 = 0.95 ** 2
        out.append(f"\\newcommand{{\\mapT}}{{{MAP_T}}}")
        out.append(f"\\newcommand{{\\mapTeq}}{{{MAP_T / l2:.1f}}}")
        out.append(f"\\newcommand{{\\mapEpsFactor}}{{{1 / l2:.3f}}}")
        out.append(f"\\newcommand{{\\mapEpsKJ}}{{{0.774908 / l2:.4f}}}")          # TIP4P/2005 eps = 0.774908 kJ/mol
        out.append(f"\\newcommand{{\\mapP}}{{{1 / l2:.3f}}}")
        out.append(f"\\newcommand{{\\mapRho}}{{{float(chk[0]['density_g_cm3']):.5f}}}")
        out.append(f"\\newcommand{{\\mapRhoErr}}{{{float(chk[0]['sem_g_cm3']):.5f}}}")
    # comparison with an independent simulation of the same model (Horstmann & Vogel 2021, SI Fig. S3, q = 0.90,
    # digitized: data/literature/horstmann2021_figS3_isobars_digitized.json) and its critical point (SI Table S1)
    hv_path = os.path.join(BASE, "data", "literature", "horstmann2021_figS3_isobars_digitized.json")
    if os.path.exists(hv_path) and "t4p2005_l0.90" in ok:
        import json
        import numpy as np
        hv = sorted(json.load(open(hv_path))["0.90"])
        hT = np.array([t for t, _ in hv]); hR = np.array([r for _, r in hv]) / 1000.0
        diffs = []
        for d in dens:
            T_ = float(d["T_K"])
            if d["model"] == "t4p2005_l0.90" and 180 <= T_ <= 280 and hT.min() <= T_ <= hT.max():
                diffs.append(abs(float(d["density_g_cm3"]) - float(np.interp(T_, hT, hR))))
        out.append(f"\\newcommand{{\\hvMaxDiffNine}}{{{max(diffs):.4f}}}")      # g/cm3, ours vs theirs, 180-280 K
        out.append(f"\\newcommand{{\\hvNptsNine}}{{{len(diffs)}}}")
        HV_TC_090 = 137.1          # K, liquid-liquid critical point for q = 0.90 (Horstmann & Vogel 2021, SI Table S1)
        out.append(f"\\newcommand{{\\tmdAboveTcNine}}{{{ok['t4p2005_l0.90'] - HV_TC_090:.0f}}}")
    # sensitivity of T_MD to the fit choice: quadratic +-25 K, cubic +-45 K, quartic +-45 K vs the cubic +-35 K
    def fit_tmd_simple(T, r, s, win, deg):
        im = int(np.argmax(r)); sel = np.abs(T - T[im]) <= win
        if sel.sum() < deg + 2:
            return None
        g = np.linspace(T[sel].min(), T[sel].max(), 4001)
        y = np.polyval(np.polyfit(T[sel], r[sel], deg, w=1 / s[sel]), g)
        k = int(np.argmax(y))
        return g[k] if 0 < k < len(g) - 1 else None
    devs = {}
    for m in ok:
        rr = sorted((float(d["T_K"]), float(d["density_g_cm3"]), float(d["sem_g_cm3"])) for d in dens
                    if d["model"] == m and d.get("used_in_fits_and_figures", "yes") == "yes")
        T_, r_, s_ = (np.array(v) for v in zip(*rr))
        base = fit_tmd_simple(T_, r_, s_, 35, 3)
        alts = [fit_tmd_simple(T_, r_, s_, w, dg) for w, dg in ((25, 2), (45, 3), (45, 4))]
        devs[m] = max(abs(a - base) for a in alts if a is not None)
    out.append(f"\\newcommand{{\\fitSysMax}}{{{max(v for m, v in devs.items() if m != 't4p2005_l0.90'):.0f}}}")
    out.append(f"\\newcommand{{\\fitSysNine}}{{{devs.get('t4p2005_l0.90', float('nan')):.0f}}}")
    out.append(f"\\newcommand{{\\fitSysOne}}{{{devs.get('t4p2005_l1.00', float('nan')):.0f}}}")
    # drift check: |first-half mean - second-half mean| in units of its standard error (about 2 x sem)
    used_runs = [d for d in dens if "_dt" not in d["model"] and d.get("used_in_fits_and_figures", "yes") == "yes"]
    z = [abs(float(d["first_half"]) - float(d["second_half"])) / (2 * float(d["sem_g_cm3"])) for d in used_runs]
    out.append(f"\\newcommand{{\\driftMax}}{{{max(z):.1f}}}")
    out.append(f"\\newcommand{{\\nUsed}}{{{len(used_runs)}}}")
    # four-bonded fraction at the maximum (range over models), and the bond gain of TIP4P/2005 over its own range
    f4 = [float(r["frac4_at_TMD"]) for m, r in rows.items() if m in ok and r.get("frac4_at_TMD") not in ("", "nan")]
    out.append(f"\\newcommand{{\\fourMin}}{{{100 * min(f4):.0f}}}")
    out.append(f"\\newcommand{{\\fourMax}}{{{100 * max(f4):.0f}}}")
    hb1 = sorted((float(d["T_K"]), float(d["hbonds_per_molecule"])) for d in dens if d["model"] == "t4p2005_l1.00")
    out.append(f"\\newcommand{{\\hbGainOne}}{{{hb1[0][1] - hb1[-1][1]:.1f}}}")
    out.append(f"\\newcommand{{\\hbRangeOne}}{{{hb1[-1][0] - hb1[0][0]:.0f}}}")
    # largest |TIP4P/2005 - real water| between 260 and 320 K, in per cent
    import numpy as np
    exp = np.loadtxt(os.path.join(BASE, "data", "real_water_density_1atm.csv"), delimiter=",", skiprows=1, usecols=(0, 1))
    dev = [abs(float(d["density_g_cm3"]) / np.interp(float(d["T_K"]), exp[:, 0], exp[:, 1]) - 1) for d in dens
           if d["model"] == "t4p2005_l1.00" and 260 <= float(d["T_K"]) <= 320]
    out.append(f"\\newcommand{{\\matchMaxPct}}{{{100 * max(dev):.2f}}}")
    # bond count at the maximum: weakest vs strongest bracketed dial setting, and a single model's gain over that span
    dial_ok = [m for m in ("t4p2005_l0.90", "t4p2005_l0.93", "t4p2005_l0.95") if rows.get(m, {}).get("status") == "ok"]
    if dial_ok and rows.get("t4p2005_l1.05", {}).get("status") == "ok":
        weak = dial_ok[0]
        dh = float(rows[weak]["hbonds_at_TMD"]) - float(rows["t4p2005_l1.05"]["hbonds_at_TMD"])
        out.append(f"\\newcommand{{\\hbSpreadDial}}{{{dh:.2f}}}")
        span = float(rows["t4p2005_l1.05"]["TMD_K"]) - float(rows[weak]["TMD_K"])
        ref = [(float(d["T_K"]), float(d["hbonds_per_molecule"])) for d in dens
               if d["model"] == "t4p2005_l1.00" and d["hbonds_per_molecule"] != "nan"]
        import numpy as np
        slope = np.polyfit([x for x, _ in ref], [y for _, y in ref], 1)[0]
        out.append(f"\\newcommand{{\\tmdSpan}}{{{span:.0f}}}")
        out.append(f"\\newcommand{{\\hbGainSpan}}{{{abs(slope) * span:.1f}}}")
    # ranges quoted in the text
    if hbs:
        out.append(f"\\newcommand{{\\hbMaxMin}}{{{min(hbs):.2f}}}")
        out.append(f"\\newcommand{{\\hbMaxMax}}{{{max(hbs):.2f}}}")
    prod = [d for d in dens if "_dt" not in d["model"]]          # production runs (not the time-step checks)
    used = [d for d in prod if d.get("used_in_fits_and_figures", "yes") != "yes"]
    out.append(f"\\newcommand{{\\nRuns}}{{{len(prod)}}}")
    out.append(f"\\newcommand{{\\nSluggish}}{{{len(used)}}}")
    # which models had sluggish runs, e.g. "TIP3P below $-$83, SPC/E below $-$53 and $\lambda=1.05$ below $-$3\,$^\circ$C"
    names = {"spce": "SPC/E", "tip3p": "TIP3P"}
    parts = []
    for model in sorted({d["model"] for d in used}):
        bad = [float(d["T_K"]) for d in used if d["model"] == model]
        lamtxt = {"t4p2005_l0.97": "0.975", "t4p2005_l0.93": "0.925"}.get(model, model.split("_l")[-1])
        nm = names.get(model, f"$\\lambda={lamtxt}$")
        parts.append(f"{nm} at or below {signed(max(bad) - 273.15)}\\,$^\\circ$C")
    txt = ", ".join(parts[:-1]) + (" and " if len(parts) > 1 else "") + parts[-1] if parts else "none"
    out.append(f"\\newcommand{{\\sluggishList}}{{{txt}}}")
    good = [d for d in prod if d.get("used_in_fits_and_figures", "yes") == "yes"]
    tmin = min(float(d["T_K"]) for d in good); tmax = max(float(d["T_K"]) for d in good)   # range actually used
    sems = [float(d["sem_g_cm3"]) for d in good]
    out.append(f"\\newcommand{{\\semMin}}{{{min(sems):.4f}}}")       # error bars of the runs used
    out.append(f"\\newcommand{{\\semMax}}{{{max(sems):.4f}}}")
    for model, key in KEYS.items():
        ts = [float(d["T_K"]) for d in good if d["model"] == model]
        if ts:
            out.append(f"\\newcommand{{\\TminC{key}}}{{{signed(min(ts) - 273.15)}}}")
    # slope of T_MD against lambda^2 for the bracketed dial settings, per 1 % of hydrogen-bond energy
    import numpy as np
    pts = [(float(r["lambda"]) ** 2, float(r["TMD_K"])) for m, r in rows.items()
           if m.startswith("t4p2005_l") and "_dt" not in m and r["status"] == "ok"]
    if len(pts) >= 3:
        x, y = np.array(pts).T
        c = np.polyfit(x, y, 1)
        out.append(f"\\newcommand{{\\slopePerPercent}}{{{c[0] / 100:.1f}}}")
        t1 = float(rows["t4p2005_l1.00"]["TMD_K"])
        out.append(f"\\newcommand{{\\simplePerPercent}}{{{t1 / 100:.1f}}}")
        out.append(f"\\newcommand{{\\slopeRatio}}{{{c[0] / t1:.1f}}}")
        # robustness: the same fit without lambda = 0.90, the least certain maximum
        x9, y9 = np.array([p for p in pts if abs(p[0] - 0.81) > 1e-6]).T
        c9 = np.polyfit(x9, y9, 1)
        out.append(f"\\newcommand{{\\slopePerPercentNoNine}}{{{c9[0] / 100:.1f}}}")
    # time-step check: density at 1 fs minus density at 0.5 fs, lambda = 1, same temperatures
    d1 = {d["T_K"]: float(d["density_g_cm3"]) for d in dens if d["model"] == "t4p2005_l1.00"}
    d05 = {d["T_K"]: float(d["density_g_cm3"]) for d in dens if d["model"] == "t4p2005_l1.00_dt05"}
    common = sorted(set(d1) & set(d05))
    if common:
        diffs = [d1[t] - d05[t] for t in common]
        out.append(f"\\newcommand{{\\dtOffset}}{{{np.mean(diffs):.4f}}}")
        if len(common) == 3:
            # parabola through the three temperatures, for each time step: does the maximum move?
            def vertex(dd):
                Ts = np.array([float(t) for t in common]); rs = np.array([dd[t] for t in common])
                c2 = np.polyfit(Ts, rs, 2)
                return -c2[1] / (2 * c2[0])
            v1, v05 = vertex(d1), vertex(d05)
            out.append(f"\\newcommand{{\\dtVertexOne}}{{{v1:.1f}}}")
            out.append(f"\\newcommand{{\\dtVertexHalf}}{{{v05:.1f}}}")
            print("3-point parabola maxima: 1 fs", round(v1, 2), " 0.5 fs", round(v05, 2))
